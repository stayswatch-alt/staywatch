-- ── Platform normalizer ──────────────────────────────────────────────
create or replace function normalize_platform(p text)
returns text
language sql
immutable
as $$
  select case
    when p is null or trim(p) = '' then 'Other'
    when lower(replace(replace(p, ' ', ''), '(', '')) like '%xtwitter%'
      or lower(p) in ('x', 'twitter') then 'X (Twitter)'
    when lower(p) like '%instagram%' then 'Instagram'
    when lower(p) like '%tiktok%' then 'TikTok'
    when lower(p) like '%youtube%' then 'YouTube'
    when lower(p) like '%facebook%' then 'Facebook'
    when lower(p) like '%threads%' then 'Threads'
    else p
  end;
$$;

-- Normalize existing rows
update incidents set platform = normalize_platform(platform);

